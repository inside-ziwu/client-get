"""真实 PostgreSQL 上的客户池修复回滚测试。"""

import os
from unittest.mock import MagicMock, patch

import pytest
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine

from app.workers.wmt_lineage_repair import run_wmt_lineage_repair_on_connection


@pytest.mark.asyncio
async def test_full_pool_is_instance_scoped_manual_safe_stale_clean_and_idempotent():
    database_url = os.getenv("TEST_DATABASE_URL")
    if not database_url:
        pytest.skip("未设置 TEST_DATABASE_URL")

    engine = create_async_engine(database_url)
    settings = MagicMock(instance_id="instance-a")
    try:
        async with engine.connect() as conn:
            transaction = await conn.begin()
            try:
                await conn.execute(text("""
                    CREATE TEMP TABLE tenants (
                      id uuid PRIMARY KEY,
                      status text NOT NULL,
                      industry text NOT NULL,
                      instance_id text NOT NULL
                    )
                """))
                await conn.execute(text("""
                    CREATE TEMP TABLE waimaotong_clean_companies (
                      id bigint PRIMARY KEY,
                      source_id text,
                      contacts_count integer,
                      domain text,
                      industry text,
                      product_tags jsonb
                    )
                """))
                await conn.execute(text("""
                    CREATE TEMP TABLE tenant_companies (
                      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      tenant_id uuid NOT NULL,
                      clean_company_id bigint NOT NULL,
                      business_status text NOT NULL,
                      data_status text NOT NULL,
                      updated_at timestamptz NOT NULL DEFAULT now(),
                      UNIQUE (tenant_id, clean_company_id)
                    )
                """))
                await conn.execute(text("""
                    INSERT INTO tenants (id, status, industry, instance_id) VALUES
                      ('11111111-1111-1111-1111-111111111111', 'active', 'PCB', 'instance-a'),
                      ('22222222-2222-2222-2222-222222222222', 'active', 'PCB', 'instance-b'),
                      ('33333333-3333-3333-3333-333333333333', 'active', 'SaaS', 'instance-a')
                """))
                await conn.execute(text("""
                    INSERT INTO waimaotong_clean_companies
                      (id, source_id, contacts_count, domain, industry, product_tags) VALUES
                      (1, 'wmt-1', 2, 'buyer.example', 'PCB', '[]'::jsonb),
                      (2, 'manual-private', 1, 'private.example', 'PCB', '[]'::jsonb)
                """))
                await conn.execute(text("""
                    INSERT INTO tenant_companies
                      (tenant_id, clean_company_id, business_status, data_status)
                    VALUES
                      ('11111111-1111-1111-1111-111111111111', 999, 'new', 'ready')
                """))

                with patch(
                    "app.workers.wmt_lineage_repair.get_settings",
                    return_value=settings,
                ):
                    first = await run_wmt_lineage_repair_on_connection(conn)
                    second = await run_wmt_lineage_repair_on_connection(conn)

                rows = (
                    await conn.execute(
                        text("""
                            SELECT tenant_id::text, clean_company_id
                            FROM tenant_companies
                            ORDER BY tenant_id, clean_company_id
                        """)
                    )
                ).all()
                assert rows == [("11111111-1111-1111-1111-111111111111", 1)]
                assert first["fan_out"] == 1
                assert first["deleted_stale"] == 1
                assert second["fan_out"] == 0
                assert second["deleted_stale"] == 0
            finally:
                await transaction.rollback()
    finally:
        await engine.dispose()
